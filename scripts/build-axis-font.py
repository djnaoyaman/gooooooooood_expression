"""Build an original, intentionally geometric variable specimen font. No external font asset."""
from pathlib import Path
from tempfile import TemporaryDirectory
from itertools import product
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.designspaceLib import DesignSpaceDocument,AxisDescriptor,SourceDescriptor
from fontTools.varLib import build
import base64
patterns={'E':['11111','10000','10000','11110','10000','10000','11111'],'X':['10001','10001','01010','00100','01010','10001','10001'],'P':['11110','10001','10001','11110','10000','10000','10000'],'R':['11110','10001','10001','11110','10100','10010','10001'],'S':['01111','10000','10000','01110','00001','00001','11110'],'I':['11111','00100','00100','00100','00100','00100','11111'],'O':['01110','10001','10001','10001','10001','10001','01110'],'N':['10001','11001','11001','10101','10011','10011','10001'],'A':['01110','10001','10001','11111','10001','10001','10001']}
with TemporaryDirectory() as tmp:
 d=DesignSpaceDocument()
 for tag,name,lo,default,hi in [('wdth','Width',75,100,125),('slnt','Slant',-12,0,0),('opsz','Optical',10,10,72)]:
  a=AxisDescriptor();a.tag=tag;a.name=name;a.minimum=lo;a.default=default;a.maximum=hi;d.addAxis(a)
 order=['.notdef','space']+list(patterns)
 for i,(wd,sl,op) in enumerate(product([75,100,125],[-12,0],[10,72])):
  fb=FontBuilder(1000,isTTF=True);fb.setupGlyphOrder(order);fb.setupCharacterMap({32:'space',**{ord(k):k for k in patterns}});glyphs={};metrics={}
  for name in order:
   pen=TTGlyphPen(None)
   for row,bits in enumerate(patterns.get(name,[])):
    for col,bit in enumerate(bits):
     if bit=='0':continue
     stroke=90-(op-10)/62*22
     coords=[(col*100,700-row*100),(col*100+stroke,700-row*100),(col*100+stroke,700-row*100+stroke),(col*100,700-row*100+stroke)]
     points=[(round((x+50)*wd/100-y*sl/60),y) for x,y in coords]
     pen.moveTo(points[0]);[pen.lineTo(p) for p in points[1:]];pen.closePath()
   glyphs[name]=pen.glyph();metrics[name]=(round((600+(72-op)*.6)*wd/100),0)
  fb.setupGlyf(glyphs);fb.setupHorizontalMetrics(metrics);fb.setupHorizontalHeader(ascent=900,descent=-100);fb.setupNameTable({'familyName':'Expression Axis Study','styleName':'Regular','uniqueFontIdentifier':'GEAxisStudy'+str(i),'fullName':'Expression Axis Study','psName':'ExpressionAxisStudy'});fb.setupOS2(sTypoAscender=900,sTypoDescender=-100,usWinAscent=900,usWinDescent=100);fb.setupPost();path=Path(tmp)/f'm{i}.ttf';fb.save(path)
  s=SourceDescriptor();s.path=str(path);s.name=f'm{i}';s.location={'Width':wd,'Slant':sl,'Optical':op};d.addSource(s)
 font,_,_=build(d);out=Path(tmp)/'axis.ttf';font.save(out)
 root=Path(__file__).resolve().parents[1]
 (root/'dist/axis-font-data.js').write_text('/* Original geometric specimen font. Generated by scripts/build-axis-font.py. */\nexport const axisFont="data:font/ttf;base64,'+base64.b64encode(out.read_bytes()).decode()+'";\n')
 print('Generated original variable font',len(out.read_bytes()),'bytes; wdth, slnt, opsz')
